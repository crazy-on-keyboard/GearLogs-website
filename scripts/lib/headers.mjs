// The site's HTTP headers from ONE source (Stage 2 PR-1, 2026-09-27): named policies → dist/_headers at build time, and the
// SAME rules resolved per request by the local preview, so what the Director reviews on :4173 answers exactly as Cloudflare
// Pages will (the preview used to apply no policy at all, so a CSP that breaks a page was only seen after the deploy).
// Pure module: no filesystem, no side effects.

/** The Content-Security-Policy directives shared by every page, before a page's own additions. */
const BASE_CSP = {
  'default-src': ["'self'"],
  'script-src': ["'self'", 'https://static.cloudflareinsights.com'],
  // no 'unsafe-inline': every inline style left the pages in PR-1; the build refuses a new one
  'style-src': ["'self'"],
  // no https: — the site's pictures are its own files
  'img-src': ["'self'", 'data:'],
  'font-src': ["'self'"],
  'connect-src': ["'self'", 'https://cloudflareinsights.com', 'https://static.cloudflareinsights.com'],
  'object-src': ["'none'"],
  'base-uri': ["'self'"],
  'form-action': ["'self'"],
  'frame-ancestors': ["'none'"],
  'upgrade-insecure-requests': [],
};

const csp = (directives) => Object.entries(directives).map(([k, v]) => (v.length ? `${k} ${v.join(' ')}` : k)).join('; ');

/** The base policy with a page's additions; a directive the base lacks (frame-src) follows connect-src, as Stage 1 wrote it. */
function withAdded(extra) {
  const out = {};
  for (const [k, v] of Object.entries(BASE_CSP)) {
    out[k] = [...v, ...(extra[k] ?? [])];
    if (k === 'connect-src' && extra['frame-src']) out['frame-src'] = extra['frame-src'];
  }
  return out;
}

