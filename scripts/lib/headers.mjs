/** dist/_headers — one block per path, the note as a comment. */
export function renderHeaders(rules = RULES) {
  const out = ['# GENERATED by scripts/build-site.mjs from scripts/lib/headers.mjs — edit the policies there, never this file.', ''];
  for (const rule of rules) {
    for (const path of rule.paths) {
      out.push(path, `  # ${rule.note}`);
      for (const name of rule.detach) out.push(`  ! ${name}`);
      for (const [name, value] of Object.entries(rule.set)) out.push(`  ${name}: ${value}`);
      out.push('');
    }
  }
  return out.join('\n');
}

/** The headers Pages answers for a request path: every matching rule in order, a detach removing what an earlier one set. */
export function headersFor(pathname, rules = RULES) {
  const result = new Map();
  for (const rule of rules) {
    const hit = rule.paths.some((p) => (p === '/*' ? true : p.endsWith('/*') ? pathname.startsWith(p.slice(0, -1)) : p === pathname));
    if (!hit) continue;
    for (const name of rule.detach) result.delete(name.toLowerCase());
    for (const [name, value] of Object.entries(rule.set)) result.set(name.toLowerCase(), [name, value]);
  }
  return [...result.values()];
}
